#!/usr/bin/env python3
"""Turn the transparent item cut-outs into game assets.

Usage: python3 tools/make_icons.py <cutout_dir>
Reads  <cutout_dir>/<item>.png  (512 px, from tools/cutout.py)
Writes assets/items/<item>.webp  (512 px master copies kept in the repo)
       src/icons.js              (192 px WebP data URIs embedded in index.html)
"""
import base64
import io
import os
import sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ITEMS = ['perfume', 'passport', 'console', 'kit', 'organizer', 'towel', 'jewelry', 'lid', 'divider']
src = sys.argv[1]
os.makedirs(os.path.join(ROOT, 'assets', 'items'), exist_ok=True)

entries = []
for name in ITEMS:
    im = Image.open(os.path.join(src, name + '.png')).convert('RGBA')
    im.save(os.path.join(ROOT, 'assets', 'items', name + '.webp'), 'WEBP', quality=90, method=6)
    small = im.resize((192, 192), Image.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, 'WEBP', quality=86, method=6)
    data = base64.b64encode(buf.getvalue()).decode('ascii')
    entries.append(f"    {name}: 'data:image/webp;base64,{data}'")
    print(name, len(buf.getvalue()) // 1024, 'KB')

with open(os.path.join(ROOT, 'src', 'icons.js'), 'w') as f:
    f.write('/* GENERATED by tools/make_icons.py — tray icons cut from the item art (assets/items). */\n')
    f.write('(function (global) {\n  global.PJ_ICONS = {\n' + ',\n'.join(entries) + '\n  };\n})(typeof window !== \'undefined\' ? window : globalThis);\n')
