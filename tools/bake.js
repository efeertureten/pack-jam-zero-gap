#!/usr/bin/env node
/* Bake the 100-level book: find a {variant, attempt} for every level that
   generates, verifies and carries the level's signature items, then write
   src/levels.baked.js (used by the game) and levels.json (design data).
   Usage: node tools/bake.js            (all 100)
          node tools/bake.js 40 60      (a range; merges into existing bake) */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
require(path.join(ROOT, 'src/engine.js'));
require(path.join(ROOT, 'src/levels.js'));
const PJ = globalThis.PJ;
const bakedFile = path.join(ROOT, 'src/levels.baked.js');

const from = +process.argv[2] || 1, to = +process.argv[3] || 100;
let baked = {};
if (fs.existsSync(bakedFile) && (from !== 1 || to !== 100)) {
  const m = fs.readFileSync(bakedFile, 'utf8').match(/PJ\.BAKED = (\{[\s\S]*?\});/);
  if (m) baked = JSON.parse(m[1]);
}

const has = (lv, fn) => lv.queue.some(q => q.type === 'block' && fn(q));
function mustHave(n, lv) {
  if (n >= 4 && n <= 6 && !has(lv, q => q.item === 'console')) return 'console intro';
  if (n === 18 && !has(lv, q => q.item === 'kit')) return 'kit intro';
  if (n === 21 && !has(lv, q => q.item === 'passport' && q.axis !== 'free')) return 'locked passport intro';
  if (n === 31 && !has(lv, q => q.item === 'console' && q.axis !== 'free')) return 'locked console intro';
  if (n >= 71 && n <= 89 && !has(lv, q => q.item === 'organizer')) return 'organizer missing';
  return null;
}

const rows = [];
const t0 = Date.now();
for (let n = from; n <= to; n++) {
  let found = null, why = '';
  for (let v = 0; v < 24 && !found; v++) {
    const cfg = Object.assign(PJ.designLevel(n, v), { attempts: 1500 });
    const lv = PJ.generateLevel(cfg);
    if (!lv) { why = 'no level'; continue; }
    const miss = mustHave(n, lv);
    if (miss) { why = miss; continue; }
    found = { v, lv, cfg };
  }
  if (!found) { console.error(`L${n}: FAILED (${why})`); process.exitCode = 1; continue; }
  const { v, lv, cfg } = found;
  baked[n] = { v, a: lv.attempt };
  const items = {};
  for (const q of lv.queue) items[q.item] = (items[q.item] || 0) + 1;
  for (const b of lv.initial) if (!b.fixed) items[b.item] = (items[b.item] || 0) + 1;
  const row = {
    n, code: cfg.code, name: cfg.name, phase: cfg.phase, grid: `${lv.W}x${lv.H}`,
    fillTarget: +lv.fillTarget.toFixed(3), gaps: lv.gapCount, zeroGap: lv.gapCount === 0,
    gates: lv.gates.map(g => `${g.side}:${g.start}+${g.len}`),
    items, queue: lv.queue.length, preplaced: lv.initial.filter(b => !b.fixed).length,
    dividers: lv.initial.filter(b => b.fixed).length,
    locked: lv.queue.filter(q => q.axis && q.axis !== 'free').length,
    solutionSteps: lv.solution.length, variant: v, attempt: lv.attempt, seed: cfg.seed
  };
  rows.push(row);
  console.log(`L${String(n).padStart(3)} ${row.grid} fill ${(row.fillTarget * 100).toFixed(0).padStart(3)}% gaps ${String(row.gaps).padStart(2)} queue ${String(row.queue).padStart(2)} steps ${String(row.solutionSteps).padStart(3)} v${v}/a${lv.attempt}  ${Object.entries(items).map(([k, c]) => k + ':' + c).join(' ')}`);
}

const sorted = {};
Object.keys(baked).map(Number).sort((a, b) => a - b).forEach(k => { sorted[k] = baked[k]; });
fs.writeFileSync(bakedFile,
  '/* GENERATED by tools/bake.js — {n: {v: variant, a: attempt}} for the 100-level book. */\n' +
  '(function (global) {\n  global.PJ.BAKED = ' + JSON.stringify(sorted) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n');

if (from === 1 && to === 100) {
  fs.writeFileSync(path.join(ROOT, 'levels.json'), JSON.stringify({ generatedBy: 'tools/bake.js', levels: rows }, null, 1) + '\n');
}
console.log(`baked ${rows.length} levels in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
